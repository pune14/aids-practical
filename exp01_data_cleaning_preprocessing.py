import pandas as pd
import numpy as np
df = pd.read_excel('employee_raw_data.xlsx', sheet_name='Employees')
print('Raw Dataset:')
print(df)
print('\nShape of dataset:', df.shape)
print('\nMissing values in each column:')
print(df.isnull().sum())
df = df.drop_duplicates()
print('\nAfter removing duplicates, shape:', df.shape)
df['Salary'] = pd.to_numeric(df['Salary'], errors='coerce')
df['Age'] = df['Age'].fillna(df['Age'].median())
df['Salary'] = df['Salary'].fillna(df['Salary'].median())
df['Gender'] = df['Gender'].fillna(df['Gender'].mode()[0])
df['Department'] = df['Department'].fillna(df['Department'].mode()[0])
print('\nMissing values after treatment:')
print(df.isnull().sum())
df['Name'] = df['Name'].str.strip()
df['Gender'] = df['Gender'].str.strip().str.upper().replace({'MALE': 'Male', 'M': 'Male', 'FEMALE': 'Female'})
df['Department'] = df['Department'].str.strip().str.upper()
iso = pd.to_datetime(df['JoiningDate'].astype(str), format='%Y-%m-%d', errors='coerce')
dmy = pd.to_datetime(df['JoiningDate'].astype(str), format='%d/%m/%Y', errors='coerce')
df['JoiningDate'] = iso.fillna(dmy)
df['Age'] = df['Age'].astype(int)
print('\nUpdated data types:')
print(df.dtypes)
Q1 = df['Age'].quantile(0.25)
Q3 = df['Age'].quantile(0.75)
IQR = Q3 - Q1
lower_bound = Q1 - 1.5 * IQR
upper_bound = Q3 + 1.5 * IQR
print('\nLower bound:', lower_bound, 'Upper bound:', upper_bound)
df['Age'] = np.where(df['Age'] > upper_bound, upper_bound, np.where(df['Age'] < lower_bound, lower_bound, df['Age']))
df_encoded = pd.get_dummies(df, columns=['Gender', 'Department'], drop_first=True)
df_encoded['Salary_Normalized'] = (df_encoded['Salary'] - np.min(df_encoded['Salary'])) / (np.max(df_encoded['Salary']) - np.min(df_encoded['Salary']))
print('\nFinal Cleaned and Preprocessed Dataset:')
print(df_encoded.to_string())
